import 'firebase_options.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  FirebaseFirestore.instance.settings = const Settings(
    persistenceEnabled: true,
    cacheSizeBytes: Settings.CACHE_SIZE_UNLIMITED,
  );
  final prefs = await SharedPreferences.getInstance();
  runApp(GymLogApp(
    prefs: prefs,
    authRepo: AuthRepository(),
    exerciseRepo: ExerciseRepository(),
    sessionRepo: SessionRepository(),
  ));
}

class GymLogApp extends StatelessWidget {
  final SharedPreferences prefs;
  final AuthRepository authRepo;
  final ExerciseRepository exerciseRepo;
  final SessionRepository sessionRepo;

  const GymLogApp({
    super.key,
    required this.prefs,
    required this.authRepo,
    required this.exerciseRepo,
    required this.sessionRepo,
  });

  @override
  Widget build(BuildContext context) {
    return MultiRepositoryProvider(
      providers: [
        RepositoryProvider.value(value: authRepo),
        RepositoryProvider.value(value: exerciseRepo),
        RepositoryProvider.value(value: sessionRepo),
      ],
      child: MultiBlocProvider(
        providers: [
          BlocProvider(create: (_) => AuthCubit(authRepo, exerciseRepo, sessionRepo)),
          // Above auth so the theme setting also applies to the login screens.
          BlocProvider(create: (_) => SettingsCubit(prefs)),
        ],
        child: BlocBuilder<AuthCubit, AuthState>(
          builder: (context, authState) {
            if (authState is AuthAuthenticated) {
              final uid = authState.user.uid;
              return MultiBlocProvider(
                providers: [
                  RepositoryProvider.value(value: uid),
                  BlocProvider(create: (_) => ExerciseLibraryCubit(exerciseRepo, uid)),
                  BlocProvider(create: (_) => SessionHistoryCubit(sessionRepo, uid)),
                  BlocProvider(create: (_) => SessionBloc(sessionRepo, uid)),
                ],
                child: const _App(home: AppShell()),
              );
            }
            // A separate MaterialApp per auth state resets navigation on
            // sign-in/out (e.g. drops the pushed email-login route).
            if (authState is AuthInitial) return const _App(home: SplashScreen());
            return const _App(home: LoginScreen());
          },
        ),
      ),
    );
  }
}

class _App extends StatelessWidget {
  final Widget home;
  const _App({required this.home});

  @override
  Widget build(BuildContext context) {
    final themeMode = context.select((SettingsCubit c) => c.state.themeMode);
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'GymLog',
      theme: AppTheme.light,
      darkTheme: AppTheme.dark,
      themeMode: themeMode,
      home: home,
    );
  }
}
